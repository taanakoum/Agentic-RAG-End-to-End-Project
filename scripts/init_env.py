"""Create a local `.env` with freshly generated secrets (never overwrites an existing file).

    python scripts/init_env.py                 # writes .env if it does not exist
    python scripts/init_env.py --force         # replaces it (asks no questions: be sure)
    python scripts/init_env.py --llm gemini    # pre-fill the LLM section for a provider

Uses only the standard library, so it runs before any dependency is installed. The generated file
works with the PostgreSQL/Redis/Qdrant of `docker-compose.dev.yml` (same password for both) as well
as with native services. Add your model API key afterwards (see the LLM section of the file).
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / ".env"

PROVIDERS = {
    # name: (base url, model, fallback models) - all speak the OpenAI chat-completions protocol
    "gemini": (
        "https://generativelanguage.googleapis.com/v1beta/openai",
        "gemini-3.5-flash-lite",
        "",
    ),
    "openrouter": (
        "https://openrouter.ai/api/v1",
        "meta-llama/llama-3.3-70b-instruct:free",
        "",
    ),
    "groq": ("https://api.groq.com/openai/v1", "llama-3.3-70b-versatile", ""),
    "none": ("", "", ""),
}

TEMPLATE = """\
# Generated by scripts/init_env.py. This file is gitignored: never commit it.

# ---------------------------------------------------------------- application
APP_ENV=dev
LOG_LEVEL=INFO

# ---------------------------------------------------------------- secrets (generated)
JWT_SECRET={jwt_secret}
MFA_ENCRYPTION_KEY={mfa_key}

# ---------------------------------------------------------------- PostgreSQL
# The same password is used by docker-compose.dev.yml (COMPOSE_POSTGRES_PASSWORD).
POSTGRES_USER=rag_app
POSTGRES_PASSWORD={pg_password}
COMPOSE_POSTGRES_PASSWORD={pg_password}
POSTGRES_HOST=127.0.0.1
POSTGRES_PORT=5432
POSTGRES_DB=rag

# ---------------------------------------------------------------- Redis and Qdrant
REDIS_URL=redis://127.0.0.1:6379/0
QDRANT_URL=http://127.0.0.1:6333

# ---------------------------------------------------------------- documents
# docling = best layout understanding (first run downloads models, slower); light = fast, simple
PDF_PIPELINE=docling
# load the search and re-ranking models when the API starts (the first question is then not slow)
WARM_MODELS_ON_STARTUP=true

# ---------------------------------------------------------------- language model (free hosted API)
# Any OpenAI-compatible endpoint works. Get a free key from the provider, paste it below, restart.
#   Gemini     https://aistudio.google.com/apikey
#   OpenRouter https://openrouter.ai/keys        (use models ending in :free)
#   Groq       https://console.groq.com/keys
LLM_BASE_URL={llm_base_url}
LLM_API_KEY=
LLM_MODEL={llm_model}
LLM_FALLBACK_MODELS={llm_fallbacks}
# Free tiers have small daily quotas and they change without notice. The application counts its own
# requests and refuses locally before the provider does (0 = unlimited). See docs/DEPLOYMENT.md.
LLM_DAILY_REQUEST_BUDGET=150
LLM_REQUESTS_PER_MINUTE=10
RL_CHAT_DAILY_LIMIT=60

# ---------------------------------------------------------------- observability (optional)
# OTEL_ENABLED=true
# OTEL_TRACES_FILE=data/logs/traces.jsonl
# OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:6006

# ---------------------------------------------------------------- frontend
FRONTEND_API_URL=http://127.0.0.1:8000/api/v1
"""


def fernet_key() -> str:
    """A valid Fernet key (32 random bytes, url-safe base64) without importing `cryptography`."""
    return base64.urlsafe_b64encode(os.urandom(32)).decode()


def render(provider: str) -> str:
    base_url, model, fallbacks = PROVIDERS[provider]
    return TEMPLATE.format(
        jwt_secret=secrets.token_urlsafe(48),
        mfa_key=fernet_key(),
        pg_password=secrets.token_urlsafe(24),
        llm_base_url=base_url,
        llm_model=model,
        llm_fallbacks=fallbacks,
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--force", action="store_true", help="overwrite an existing .env")
    parser.add_argument("--llm", choices=sorted(PROVIDERS), default="gemini")
    args = parser.parse_args()
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists; leaving it untouched (use --force to replace it).")
        return 0
    TARGET.write_text(render(args.llm), encoding="utf-8")
    print(f"Wrote {TARGET}")
    print("Next: add your LLM_API_KEY to it (optional; only answering questions needs it).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
